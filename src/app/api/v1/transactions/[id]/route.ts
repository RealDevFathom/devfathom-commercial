import { NextResponse } from 'next/server';
import { z } from 'zod';
import { withApiAuth } from '@/lib/api-auth';
import { readJson } from '@/lib/api-json';

const updateSchema = z.object({
  type: z.enum(['INCOME', 'EXPENSE']).optional(),
  amount: z.number().positive().optional(),
  description: z.string().min(1).optional(),
  category: z
    .enum([
      'SALARIES',
      'SUBSCRIPTIONS',
      'OFFICE',
      'MARKETING',
      'HOSTING',
      'SOFTWARE',
      'HARDWARE',
      'TRAVEL',
      'UTILITIES',
      'MISCELLANEOUS',
    ])
    .nullable()
    .optional(),
  projectId: z.string().nullable().optional(),
  clientId: z.string().nullable().optional(),
  date: z.string().datetime().optional(),
});

export const PATCH = withApiAuth(
  'finance:write',
  async (authCtx, request, ctx: { params: Promise<{ id: string }> }) => {
    const { id } = await ctx.params;
    const __j = await readJson(request); // REST-05
    if (!__j.ok) return __j.response;
    const body = __j.data;
    const parsed = updateSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json(
        { error: 'Invalid input', details: parsed.error.issues },
        { status: 400 }
      );
    }
    const existing = await authCtx.db.transaction.findUnique({
      where: { id },
      select: { id: true, paymentId: true },
    });
    if (!existing) return NextResponse.json({ error: 'Transaction not found' }, { status: 404 });

    const { date, ...data } = parsed.data;

    // DEV-166: payment-linked ledger entries mirror an invoice payment; their accounting
    // fields must be changed through the payment, not directly.
    if (
      existing.paymentId &&
      (data.type !== undefined ||
        data.amount !== undefined ||
        date !== undefined ||
        data.clientId !== undefined ||
        data.projectId !== undefined)
    ) {
      return NextResponse.json(
        { error: 'This entry is generated by an invoice payment. Edit the payment instead.' },
        { status: 409 }
      );
    }

    // Foreign-key constraints only prove that a referenced row exists; they do
    // not prove that it belongs to the token's workspace. Keep nullable fields
    // clearable, but explicitly scope every supplied reference before updating.
    if (
      data.projectId &&
      !(await authCtx.db.project.findFirst({
        where: { id: data.projectId, organizationId: authCtx.organizationId },
        select: { id: true },
      }))
    ) {
      return NextResponse.json({ error: 'projectId does not exist.' }, { status: 400 });
    }
    if (
      data.clientId &&
      !(await authCtx.db.client.findFirst({
        where: { id: data.clientId, organizationId: authCtx.organizationId },
        select: { id: true },
      }))
    ) {
      return NextResponse.json({ error: 'clientId does not exist.' }, { status: 400 });
    }

    const transaction = await authCtx.db.transaction.update({
      where: { id },
      data: { ...data, ...(date && { date: new Date(date) }) },
    });
    return NextResponse.json({ data: transaction });
  }
);

export const DELETE = withApiAuth(
  'finance:write',
  async (authCtx, _request, ctx: { params: Promise<{ id: string }> }) => {
    const { id } = await ctx.params;
    const existing = await authCtx.db.transaction.findUnique({
      where: { id },
      select: { id: true, paymentId: true },
    });
    if (!existing) return NextResponse.json({ error: 'Transaction not found' }, { status: 404 });
    // DEV-166: payment-linked entries can only be removed by deleting the payment.
    if (existing.paymentId) {
      return NextResponse.json(
        { error: 'This entry is generated by an invoice payment. Delete the payment instead.' },
        { status: 409 }
      );
    }
    await authCtx.db.transaction.delete({ where: { id } });
    return NextResponse.json({ success: true });
  }
);
