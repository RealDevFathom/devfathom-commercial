import { beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
  can: vi.fn(async () => true),
  transactionFindUnique: vi.fn(),
  transactionUpdate: vi.fn(),
  transactionDelete: vi.fn(),
}));

vi.mock('server-only', () => ({}));
vi.mock('@/lib/abac', async () => ({
  ...(await vi.importActual<typeof import('@/lib/abac')>('@/lib/abac')),
  can: mocks.can,
}));
vi.mock('@/lib/entitlements', () => ({ hasModule: vi.fn(() => true) }));
vi.mock('../activity', () => ({ logActivity: vi.fn() }));
vi.mock('@/lib/webhooks', () => ({ emitEvent: vi.fn() }));
vi.mock('../audit', () => ({
  ipFromHeaders: vi.fn(() => null),
  isAuditExcludedPath: vi.fn(() => true),
  recordTrpcAudit: vi.fn(),
}));

import type { TRPCContext } from '../trpc';
import { financeRouter } from './finance';

function caller() {
  return financeRouter.createCaller({
    db: {
      transaction: {
        findUnique: mocks.transactionFindUnique,
        update: mocks.transactionUpdate,
        delete: mocks.transactionDelete,
      },
    },
    entitlements: { organizationId: 'org-1', enabledModules: [], modules: [] },
    session: {
      expires: 'later',
      user: { id: 'admin-1', role: 'ADMIN', status: 'ACTIVE', organizationId: 'org-1' },
    },
    organization: { id: 'org-1' },
    support: null,
    requestMeta: { ip: null, userAgent: null },
    audit: { detail: {} },
  } as unknown as TRPCContext);
}

describe('finance payment-linked ledger entries', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mocks.can.mockResolvedValue(true);
  });

  it('refuses to delete a transaction generated by an invoice payment', async () => {
    mocks.transactionFindUnique.mockResolvedValue({ id: 'tx-1', paymentId: 'payment-1' });

    await expect(caller().deleteTransaction({ id: 'tx-1' })).rejects.toMatchObject({
      code: 'BAD_REQUEST',
    });
    expect(mocks.transactionDelete).not.toHaveBeenCalled();
  });

  it('still deletes a manually entered transaction', async () => {
    mocks.transactionFindUnique.mockResolvedValue({ id: 'tx-2', paymentId: null });
    mocks.transactionDelete.mockResolvedValue({ id: 'tx-2' });

    await caller().deleteTransaction({ id: 'tx-2' });
    expect(mocks.transactionDelete).toHaveBeenCalledWith({ where: { id: 'tx-2' } });
  });

  it('refuses to change the amount of a payment-generated transaction', async () => {
    mocks.transactionFindUnique.mockResolvedValue({ id: 'tx-1', paymentId: 'payment-1' });

    await expect(caller().updateTransaction({ id: 'tx-1', amount: 5 })).rejects.toMatchObject({
      code: 'BAD_REQUEST',
    });
    expect(mocks.transactionUpdate).not.toHaveBeenCalled();
  });

  it('allows a description edit on a payment-generated transaction', async () => {
    mocks.transactionFindUnique.mockResolvedValue({ id: 'tx-1', paymentId: 'payment-1' });
    mocks.transactionUpdate.mockResolvedValue({ id: 'tx-1' });

    await caller().updateTransaction({ id: 'tx-1', description: 'Renamed' });
    expect(mocks.transactionUpdate).toHaveBeenCalledWith({
      where: { id: 'tx-1' },
      data: { description: 'Renamed' },
    });
  });
});
