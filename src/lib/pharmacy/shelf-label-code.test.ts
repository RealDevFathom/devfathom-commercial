import { describe, expect, it } from 'vitest';

import {
  MAX_SHELF_LABEL_NUMBER,
  parseShelfLabelCode,
  shelfLabelBarcodeModules,
  shelfLabelBarcodeSvg,
  shelfLabelCode,
} from './shelf-label-code';

// Code128 modules for `7100000001234563` from an independent encoder
// (python-barcode 0.16.1 `Code128(code).build()`): start C, eight digit pairs,
// checksum and stop, `1` = bar module, `0` = space module.
const REFERENCE_MODULES =
  '110100111001001101000011011001100110110011001101100110011001101100111011011101011101100010100110000100010011001100011101011';

describe('DEV-90 shelf-label lot code', () => {
  it('is sixteen digits, never a GTIN length, and round-trips the lot number', () => {
    for (const labelNumber of [1, 42, 123_456, MAX_SHELF_LABEL_NUMBER]) {
      const code = shelfLabelCode(labelNumber);
      expect(code).toMatch(/^71\d{14}$/);
      expect([8, 12, 13, 14]).not.toContain(code.length);
      expect(parseShelfLabelCode(code)).toBe(labelNumber);
      expect(parseShelfLabelCode(`  ${code}\n`)).toBe(labelNumber);
    }
    expect(shelfLabelCode(123_456)).toBe('7100000001234563');
  });

  it('refuses a mistyped digit instead of resolving some other lot', () => {
    const code = shelfLabelCode(123_456);
    const typo = `${code.slice(0, 10)}${(Number(code[10]) + 1) % 10}${code.slice(11)}`;
    expect(parseShelfLabelCode(typo)).toBeNull();
    const swapped = `${code.slice(0, -1)}${(Number(code.at(-1)) + 1) % 10}`;
    expect(parseShelfLabelCode(swapped)).toBeNull();
  });

  it('does not treat ordinary barcodes or text as a shelf label', () => {
    for (const value of ['8964000123456', '08964000123456', 'Panadol', '71', '7100000000000000']) {
      expect(parseShelfLabelCode(value)).toBeNull();
    }
  });

  it('rejects lot numbers outside the stored range', () => {
    for (const value of [0, -1, 1.5, MAX_SHELF_LABEL_NUMBER + 1, Number.NaN]) {
      expect(() => shelfLabelCode(value)).toThrow(/outside the supported range/);
    }
  });

  it('encodes ISO/IEC 15417 Code128 set C exactly as an independent encoder does', () => {
    // Reference modules generated by python-barcode's Code128 for the same code.
    expect(shelfLabelBarcodeModules('7100000001234563')).toBe(REFERENCE_MODULES);
    expect(shelfLabelBarcodeModules('7100000001234563')).toHaveLength(123);
    expect(() => shelfLabelBarcodeModules('7100000001234560')).toThrow(/Invalid internal/);
  });

  it('renders a monochrome SVG with quiet zones', () => {
    const svg = shelfLabelBarcodeSvg('7100000001234563', 34, 6);
    expect(svg).toContain('viewBox="0 0 143 20"');
    expect(svg).toContain('width="34mm" height="6mm"');
    expect(svg).toContain('<rect x="10" y="0" width="2" height="20"/>');
    expect(svg).not.toMatch(/<script|on\w+=/i);
  });
});
